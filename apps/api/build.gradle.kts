// Deliberately rewrites apps/api/openapi/openapi.json from the running test application (T024/T025).
// The regular `test` task only compares against the committed snapshot and never writes it.
tasks.register<Test>("refreshOpenApiSnapshot") {
    group = "documentation"
    description = "Regenerates openapi/openapi.json from the application's OpenAPI document."
    testClassesDirs = sourceSets["test"].output.classesDirs
    classpath = sourceSets["test"].runtimeClasspath
    useJUnitPlatform()
    filter {
        includeTestsMatching("com.tripdesk.api.contract.OpenApiSnapshotTest")
    }
    systemProperty("openapi.snapshot.refresh", "true")
    outputs.upToDateWhen { false }
}
